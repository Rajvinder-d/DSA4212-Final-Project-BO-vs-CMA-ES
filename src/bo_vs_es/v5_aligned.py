"""Focused V5 extension with V4's design and search randomness.

Planning imports NumPy only. Scientific execution delegates to the unchanged
followup_v4 module; its platform-specific launcher and full grid are not used.
"""
import hashlib
import json
import random

import numpy as np

from bo_vs_es import ROOT

DEFAULT_CONFIG = ROOT / 'configs/followup_v5/boundary_comparison_v4_aligned.json'
REFERENCE = ROOT / 'configs/followup_v5/v4_reference.json'


def validate_config(config):
    """Freeze the scientific design, allowing a separate collection name."""
    expected = dict(executor='v4-aligned-v1',
        protocol='configs/protocols/rotation_battery_v1.json',
        initial_design_seeds=list(range(20, 40)), namespace=4107, scheduling_seed=5107,
        cma_search_replicates=list(range(5)), n_init=20, budget=300,
        checkpoints=[100, 300], lengthscale_upper=5.0,
        methods=['bo_iso', 'bo_ard', 'bo_iso_pool', 'random', 'cma_full'],
        cma_handlers=['resample', 'project'],
        pool=dict(interior=2048, surface=2048, chunk_size=256),
        targets_rmse_v=[.01, .006], bootstrap_seed=5129, bootstrap_resamples=10000)
    if {k: v for k, v in config.items() if k not in {'id', 'status'}} != expected:
        raise ValueError('Aligned V5 settings changed; version the design before changing its specification')
    name = config['id']
    if (not name or name in {'.', '..'} or any(c not in
            'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_' for c in name)):
        raise ValueError('Collection ID must contain only letters, digits, hyphens and underscores')
    if name in {'boundary-comparison-v5', 'boundary-comparison-v5-jax', 'boundary-v5-windows-jax'}:
        raise ValueError('Use a separate collection from original V5')


def matching_search_seed(config, design, replicate):
    """V4's kind-1 stream, reproduced here to keep planning free of Torch.

    Parity tests compare this calculation directly with followup_v4.search_seed.
    All actual candidate streams are generated by the frozen V4 executor.
    """
    rng = np.random.default_rng(np.random.SeedSequence(
        [config['namespace'], design, replicate, 0, 1]))
    return int(rng.integers(1, 2**31 - 1))


def jobs_for(config):
    validate_config(config)
    jobs = []
    for design in config['initial_design_seeds']:
        group = []
        for method in config['methods']:
            cma = method == 'cma_full'
            for replicate in config['cma_search_replicates'] if cma else [0]:
                seed = matching_search_seed(config, design, replicate)
                for handler in config['cma_handlers'] if cma else ['none']:
                    group.append(dict(block='battery_ball_v5_v4_aligned', objective='battery',
                        domain='ball', condition=None, initial_design_seed=design,
                        search_replicate=replicate, search_seed=seed, rotation_seed=None,
                        method=method, handler=handler, budget=config['budget'],
                        n_init=config['n_init'], checkpoints=list(config['checkpoints']),
                        lengthscale_upper=config['lengthscale_upper'], corrected=True,
                        stage='matched_extension'))
        # Scheduling never consumes a scientific stream.
        random.Random(config['scheduling_seed'] + design).shuffle(group)
        jobs.extend(group)
    return jobs


def initial_points(config, design):
    """Reconstruct V4's identity-ball initial design without an optimiser import."""
    from bo_vs_es.objectives.models import Domain
    rng = np.random.default_rng(np.random.SeedSequence(
        [config['namespace'], design, 0, 0, 0]))
    domain = Domain('ball', np.eye(5))
    return domain.to_base(domain.sample(rng, config['n_init']))


def verify_alignment(environment):
    """Reject changed V4 scientific inputs or numerical package versions."""
    reference = json.loads(REFERENCE.read_text())
    expected = dict(reference['source_sha256'])
    expected['configs/protocols/rotation_battery_v1.json'] = reference['protocol_sha256']
    expected['requirements-lock.txt'] = reference['dependency_lock_sha256']
    expected.update({f'data/processed/{name}': digest
                     for name, digest in reference['data_sha256'].items()})
    for name, digest in expected.items():
        path = ROOT / name
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError(f'V4 alignment failed: missing or changed input {name}')
    manifest = json.loads((ROOT / 'data/processed/manifest.json').read_text())
    for key, value in reference['data_settings'].items():
        if manifest.get(key) != value:
            raise ValueError(f'V4 alignment failed: changed data setting {key}')
    if manifest.get('output_sha256') != reference['data_sha256']:
        raise ValueError('V4 alignment failed: data manifest hashes differ')
    for package, version in reference['packages'].items():
        if environment.get('packages', {}).get(package) != version:
            raise ValueError(f'V4 alignment requires {package}=={version}; check requirements-reproduce.txt')
    return dict(reference_sha256=hashlib.sha256(REFERENCE.read_bytes()).hexdigest(),
        source_record_sha256=reference['source_record_sha256'],
        checked_input_files=len(expected), numerical_packages=reference['packages'],
        data_settings=reference['data_settings'],
        relationship='Matched V4 designs and scientific executor; reused designs, not independent confirmation',
        limitation='Operating system, hardware and Python build can differ; historical paths are not guaranteed')
